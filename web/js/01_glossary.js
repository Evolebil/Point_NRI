function infoIcon(term) {
  var safe = String(term).replace(/"/g, '&quot;');
  return '<button type="button" class="info-btn" data-term="' + safe +
         '" aria-label="Объяснение: ' + safe + '">ⓘ</button>';
}

// POPOVER
(function(){
  var popover = document.createElement('div');
  popover.id = 'info-popover'; popover.setAttribute('role', 'tooltip'); popover.hidden = true;
  document.body.appendChild(popover);
  var active = null;
  document.addEventListener('click', function(e){
    var button = e.target.closest && e.target.closest('.info-btn');
    if (button){
      if (active === button && !popover.hidden){ popover.hidden = true; active = null; return; }
      var term = button.getAttribute('data-term');
      popover.textContent = GLOSSARY[term] || '';
      var rect = button.getBoundingClientRect();
      popover.style.left = Math.max(8, Math.min(rect.left, window.innerWidth - 268)) + 'px';
      popover.style.top = (rect.bottom + 6) + 'px';
      popover.hidden = false; active = button; return;
    }
    popover.hidden = true; active = null;
  });
  document.addEventListener('keydown', function(e){ if (e.key === 'Escape'){ popover.hidden = true; active = null; } });
})();
