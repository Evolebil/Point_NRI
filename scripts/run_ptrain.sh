#!/bin/sh
# Обучение новой сети-бойца (ТЗ v21, этап 3): копирование бота, затем PPO. Несколько часов на ядрах − 2.
# Использование: ./run_ptrain.sh [префикс=net_runs/p1] [итераций PPO=800] [боёв в итерации=512]
# Обучение само останавливается на плато: 6 проверок подряд (300 итераций) без роста лучшего результата на 0.5 п.п.
# (DND_PATIENCE — число проверок); энтропия 0.1 (DND_ENT). В конце — проверка на 4000 боёв и честная (зеркальная) на 3000 пар.
# Повторный запуск продолжает PPO с последней контрольной точки (<префикс>.bin.state); копирование не повторяется,
# если уже есть <префикс>.bc.bin. Журнал — <префикс>.log, странные победы — <префикс>.bin.strange.txt,
# лучшая версия на отложенных боях — <префикс>.bin.best.bin (в игру её ставят копированием в net_fighter_p.bin).
P=${1:-net_runs/p1}
IT=${2:-800}
N=${3:-512}
g++ -std=c++17 -O2 -pthread -o net_fighter net_fighter.cc || exit 1
export DND_NETP=off   # бои учителя и соперников-ботов — без готовой сети из папки
if [ ! -f "$P.bc.bin" ]; then
    ./net_fighter pbc 16384 8 1 "$P.bc.bin" >> "$P.log" 2>&1 || exit 1
fi
[ -f "$P.bin" ] || cp "$P.bc.bin" "$P.bin"
./net_fighter ptrain "$IT" "$N" 7 "$P.bin" >> "$P.log" 2>&1
./net_fighter peval "$P.bin.best.bin" 4000 >> "$P.log" 2>&1
./net_fighter pfair "$P.bin.best.bin" 3000 >> "$P.log" 2>&1
