#!/bin/sh
# Обучение сетей-Сборщиков A и B. В боях обоими боссами ходит сеть-боец models/nets/net_fighter_p.bin (температура 0.25);
# Сборщик решает и «структурные» решения генератора, и числа (какое состояние, сколько раундов, дальность, размеры
# эффектов, параметры призыва). Соперники: другая сеть, её зал славы, свой зал славы, обычный генератор. Контроль раз в
# 50 итераций — 3000 сборок против случайного генератора.
# Использование: ./scripts/run_builder.sh [префикс=runs/net/builder5] [итераций=200] [сборок на сторону=768] [старт A.bin] [старт B.bin]
# (со стартовыми весами Сборщики доучиваются, старые веса не трогаются — пишется новый префикс; в игру — копией в models/nets/)
cd "$(dirname "$(readlink -f "$0")")/.." || exit 1   # корень проекта
P=${1:-runs/net/builder5}
IT=${2:-200}
M=${3:-768}
make -s build/net_builder || exit 1
mkdir -p "$(dirname "$P")"
./build/net_builder train "$IT" "$M" 1 "$P" $4 $5 >> "$P.log" 2>&1
./build/net_builder eval "${P}_A.bin" 3000 >> "$P.log" 2>&1
./build/net_builder eval "${P}_B.bin" 3000 >> "$P.log" 2>&1
