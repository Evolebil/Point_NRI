#!/bin/sh
# Этап 5 ТЗ: обучение сетей-Сборщиков A и B на ценах этапа 4. В боях обоими боссами ходит сеть-боец net_fighter_p.bin
# (температура 0.25); Сборщик решает и прежние «структурные» решения генератора, и числа (какое состояние, сколько
# раундов, дальность, размеры эффектов, параметры призыва). Соперники: другая сеть, её зал славы, свой зал славы,
# обычный генератор. Контроль раз в 50 итераций — 3000 сборок против случайного и линейного Сборщика.
# Использование: ./run_builder.sh [префикс=net_runs/builder5] [итераций=200] [сборок на сторону=768] [старт A.bin] [старт B.bin]
# (этап 5б: со стартовыми весами Сборщики доучиваются, старые веса не трогаются — пишется новый префикс)
P=${1:-net_runs/builder5}
IT=${2:-200}
M=${3:-768}
g++ -std=c++17 -O2 -pthread -o net_builder net_builder.cc || exit 1
./net_builder train "$IT" "$M" 1 "$P" $4 $5 >> "$P.log" 2>&1
./net_builder eval "${P}_A.bin" 3000 >> "$P.log" 2>&1
./net_builder eval "${P}_B.bin" 3000 >> "$P.log" 2>&1
