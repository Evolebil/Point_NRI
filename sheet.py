#!/usr/bin/env python3
"""Шпаргалка цен «коротко»: все цены и проценты при заданном бюджете, посчитанные движком (./arena_play catalog).
Использование:  python3 sheet.py [бюджет=800] > kratko-pravila.md      (play_server.py отдаёт её же на странице игры)"""
import json
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def catalog(budget):
    p = subprocess.run([os.path.join(HERE, "arena_play")], input=json.dumps({"cmd": "catalog", "budget": budget}) + "\n" + '{"cmd":"quit"}\n',
                       capture_output=True, text=True, encoding="utf-8", cwd=HERE, timeout=30)
    return json.loads(p.stdout.splitlines()[0])["data"]


def pct(x):
    return "%+d%%" % round(100 * x)


def step_price(lad, n):   # цена n-й ступени лестницы (в единицах базы)
    return lad[n] - lad[n - 1]


def sheet(budget=800):
    c = catalog(budget)
    L, K, M, U = c["ladders"], c["coef"], c["mods"], c["unit"]
    dt = c["dtypes"]
    o = []
    w = o.append
    w("# Шпаргалка цен (бюджет %d)\n" % budget)
    w("Считайте так: **цена = Σ (эффекты) × (100%% + надбавки − скидки)**, где проценты просто складываются, а скидки в сумме не больше %d%% (надбавки добавляются всегда). Всё, что не потратили, уходит в здоровье: 2 очка за 1 ХП.\n" % round(100 * (1 - M["floor"])))
    w("## 1. Тело\n")
    w("- **Характеристика V** стоит V·(V+1)/2 − 55: **десять бесплатно**, выше десяти платим, ниже десяти очки возвращаются. 6 → −34, 8 → −19, 10 → 0, 12 → +23, 14 → +50, 16 → +81, 18 → +116, 20 → +155, 24 → +245, 30 → +410, 40 → +765. От 1 (возвращает 54) до 40.")
    w("- **КД**: каждая единица a даёт +1 КД (КД = 10 + a, купить можно до 40), цена (2a)·(2a+1)/2: КД 14 → 36, КД 15 → 55, КД 18 → 136, КД 20 → 210.")
    w("- **Скорость** покупается вся, с нуля, шагами по 5 фт: 30 фт стоят %d (таблица в §4)." % U["speed30"])
    w("- **Кубики**: " + ", ".join("к%d" % d for d in c["dice"]) + "; цены считаются от среднего (грань+1)/2.")
    w("- **ХП**: 2 очка за ХП.\n")
    w("## 2. Оружие\n")
    w("Цена = **%.2f** × (урон первой атаки + **%.2f** × (атак − 1) × полный удар) × (100%% + надбавки). Урон первой атаки — кубики × средний кубик, средний кубик = (грань+1)/2 (к8 → 4.5); полный удар — кубики плюс модификатор характеристики оружия (СИЛ; фехтовальное — лучшая из СИЛ и ЛОВ; боеприпасы — ЛОВ). Модификатор первой атаки уже оплачен в характеристике. Фехтовальное +3 очка. Надбавки:\n" % (K["wpnDice"], K["wpnAtt"]))
    rows = ["| Что | Надбавка |", "|---|---|"]
    for r in (30, 60, 120):
        rows.append("| дальнее оружие %d фт | %s |" % (r, pct(K["wpnRange"] * L["range"][(r - 5) // 5])))
    for r in (10, 15, 20):
        rows.append("| досягаемость ближнего %d фт | %s |" % (r, pct(K["reach"] * (r - 5) / 5)))
    o += rows
    w("\nПример: 2к8 рубящего, 2 атаки, СИЛ 16 (+3): %.2f × (9 + %.2f × (9 + 3)) = %d очков. «+кубики к урону оружия» в правилах тоже оплачиваются за каждый удар.\n" % (K["wpnDice"], K["wpnAtt"], round(K["wpnDice"] * (9 + K["wpnAtt"] * 12))))
    w("## 3. Способность\n")
    w("**Эффекты** складываются в базу, потом база умножается на (100% + надбавки − скидки).\n")
    rows = ["| Эффект | Цена |", "|---|---|"]
    rows.append("| урон, N кубиков к6 (другая грань: считайте N·(грань+1)/7 кубиков к6 по той же строке) | " + ", ".join("%dк6 → %d" % (n, round(K["dmg"] * L["dmgDice"][n] * 1.0)) for n in (1, 2, 3, 4, 6, 8, 10)) + " |")
    cp = c["condPrice"]
    names = c["conds"]
    cheap = [(names[i], round(cp[i])) for i in range(1, len(names)) if round(cp[i]) < 60]
    dear = [(names[i], round(cp[i])) for i in range(1, len(names)) if round(cp[i]) >= 60]
    rows.append("| состояние на цель, раундов r: цена × (1 + 0.25·(r−1)); «сбит с ног» и способности без броска — без множителя. Обычные состояния (%s) | по %d–%d |" % (", ".join(n for n, _ in cheap), min(p for _, p in cheap), max(p for _, p in cheap)))
    for n, pr in dear:
        rows.append("| состояние «%s» (сильное, цена задрана симуляцией) | %d |" % (n, pr))
    rows.append("| толчок, ступени по 5 фт (5 / 10 / 20 / 30 фт) | %s |" % " / ".join(str(round(K["push"] * L["push"][n])) for n in (1, 2, 4, 6)))
    rows.append("| урон при столкновении, за 1к6 | %d |" % round(U["collide"]))
    rows.append("| урон по времени, за 1к6 в ход за раунд | %d |" % round(K["dot"]))
    rows.append("| лечение себя, за 1к6 | %d |" % round(K["heal"] * 1.0))
    rows.append("| временные хиты, кубиков к6 (1 / 2 / 4 / 6 / 10) | %s |" % " / ".join(str(round(K["temp"] * L["temp"][n])) for n in (1, 2, 4, 6, 10)))
    rows.append("| **бонус КД** и **бафф оружия** (длящиеся эффекты) | как то же самое навсегда (КД — по лестнице КД от вашего, бафф — как кубики оружия на каждый удар) × доля боя под эффектом: применений × раундов / %d, не больше 1. Скидки за применения у них нет — она уже в доле боя |" % c.get("fightRounds", 20))
    rows.append("| телепорт, ступени по 10 фт (10 / 30 / 60 фт) | %s |" % " / ".join(str(round(K["tele"] * L["tele"][n])) for n in (1, 3, 6)))
    rows.append("| невидимость, за раунд | %d |" % round(U["invis"]))
    rows.append("| тьма вокруг себя, за 10 фт радиуса | %d |" % round(U["dark"]))
    rows.append("| труднопроходимая местность | %d |" % round(U["terr"]))
    rows.append("| укрытие (скрытность) | %d |" % round(U["hide"]))
    rows.append("| **барьер**: временная стена, за каждую клетку за каждый раунд | %.1f |" % K["wall"])
    rows.append("| способность «по клетке» (область, барьер, местность в выбранной клетке) | цены те же, надбавки за дальность и область те же |")
    o += rows
    w("\n**Надбавки** (складываются):\n")
    rows = ["| Что | Надбавка |", "|---|---|"]
    for r in (30, 60, 120):
        rows.append("| дальность %d фт | %s |" % (r, pct(K["aRange"] * L["range"][(r - 5) // 5])))
    for r in (10, 15, 20, 30, 40):
        rows.append("| область, радиус %d фт | %s |" % (r, pct(K["area"] * L["area"][r // 5])))
    rows.append("| без броска попадания (всегда попадает) | %s |" % pct(M["auto"]))
    rows.append("| бонусное действие | %s |" % pct(M["bonus"]))
    o += rows
    w("\n**Скидки** (вычитаются):\n")
    rows = ["| Что | Скидка |", "|---|---|"]
    rows.append("| применений за бой: 1 / 2 / 3 / 5 | %s |" % " / ".join("−%d%%" % round(100 * M["usesAt1"] * (1 - (k - 1) * 0.2)) for k in (1, 2, 3, 5)))
    rows.append("| перезарядка 6 / 5–6 / 4–6 | %s |" % " / ".join("−%d%%" % round(100 * M["rechargeAt0"] * (1 - (7 - t) / 6)) for t in (6, 5, 4)))
    rows.append("| концентрация | доля длительности, которая теряется при срыве: по вам ~1,5 атаки за раунд, каждое попадание — спасбросок ТЕЛ СЛ 10. Чем выше ваш КД и спасбросок ТЕЛ и короче эффект, тем меньше скидка |")
    rows.append("| расходует ячейку заклинания | −%d%% |" % round(100 * M["slot"]))
    o += rows
    w("\nСкидки в сумме не больше %d%%, то есть способность нельзя удешевить больше чем на %d%% (а лимит применений вместе с ячейкой не даёт «бесплатных» заклинаний); надбавки добавляются всегда. Ячейка заклинания стоит %.0f очков за уровень, нужна способностям с ячейкой.\n" % (round(100 * (1 - M["floor"])), round(100 * (1 - M["floor"])), U["slot"]))
    w("Число способностей: первые 3 бесплатны, дальше надбавка %.1f × лестница (n = число сверх трёх): " % K["nabil"] + ", ".join("%d → %d" % (n, round(K["nabil"] * L["nabil"][n])) for n in (1, 2, 3, 4, 6, 9)) + ".\n")
    w("## 4. Пассивы\n")
    rows = ["| Пассив | Цена |", "|---|---|"]
    for p in c["passives"]:
        rows.append("| %s | %d |" % (p["label"], p["price"]))
    rows.append("| регенерация, за 1к6 в ход | %d |" % U["regen"])
    rows.append("| парирование, за +1 КД | %d |" % U["parry"])
    rows.append("| легендарное сопротивление, за 1 использование | %d |" % U["legRes"])
    rows.append("| легендарные действия, за очко | %d |" % U["legAct"])
    rows.append("| всплеск действий, за использование | %d |" % U["surge"])
    rows.append("| скорость 30 фт (покупается вся, с нуля; дальше по 5 фт дороже) | %d |" % U["speed30"])
    rows.append("| иммунитет к состоянию, за одно | %d |" % U["immCond"])
    rows.append("| владение спасброском, за одно | %d |" % U["saveProf"])
    o += rows
    w("\n**Правило «когда → что»** (ярость, добивание и т. п.): цена эффекта × доля условия — как часто оно выполняется в бою: " +
      ", ".join("%s %d%%" % (x["name"], round(100 * x["share"])) for x in c.get("whens", [])) + ".\n")
    w("\n**Резист и иммунитет к типу урона** зависят от того, как часто встречается тип: цена = коэффициент × доля типа.\n")
    rows = ["| Тип урона | Доля | Резист | Иммунитет | Уязвимость (возврат) |", "|---|---|---|---|---|"]
    for i, n in enumerate(dt):
        sh = c["dshare"][i]
        rows.append("| %s | %.1f%% | %d | %d | +%d |" % (n, 100 * sh, max(1, round(U["resist5"] * sh)), max(1, round(U["imm5"] * sh)), round(U["vuln5"] * sh)))
    o += rows
    w("\n**Аура** (действует на врагов рядом): %.1f за 1 средний урон × лестница кубиков × (100%% + надбавка за радиус); **довесок к удару**: %.1f за 1 средний доп. урон.\n" % (U["aura"], U["rdmg"]))
    w("## 5. Пример за минуту\n")
    w("Бюджет %d. СИЛ 16 (+81) + ЛОВ 10 (0) + ТЕЛ 14 (+50) + ИНТ 8 (−19) + МДР 10 (0) + ХАР 8 (−19) = 93. КД 14 = 36. Скорость 30 фт: %d. Оружие 1к8, 2 атаки: %d. Итого без способностей и ХП: %d; остаток идёт в ХП (÷2).\n" % (
        budget, U["speed30"], round(K["wpnDice"] * (4.5 + K["wpnAtt"] * 7.5)), 93 + 36 + U["speed30"] + round(K["wpnDice"] * (4.5 + K["wpnAtt"] * 7.5))))
    return "\n".join(o)


if __name__ == "__main__":
    print(sheet(int(sys.argv[1]) if len(sys.argv) > 1 else 800))
