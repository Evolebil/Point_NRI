// ============================================================================
// Сеть-Сборщик (Этап 6): рекуррентная нейросеть собирает босса, принимая решения генератора одно за другим.
//
// На каждом решении генератора (взять ли способность, сколько кубиков, какая доля бюджета на оружие и т.д.) сеть видит: какое это решение,
// исходную вероятность, бюджет, сколько потрачено и осталось, сколько способностей уже есть, номер шага, и выдаёт поправку к вероятности.
// Скрытое состояние GRU живёт всю сборку, поэтому сеть помнит, что уже решила. Генератор сам следит за бюджетом: сеть не может собрать
// недопустимого босса. Если всё же что-то ломается (босс дороже бюджета, нулевые ХП, зависший бой), это ошибка системы, и счётчик
// «системных сбоев» в логе показывает это.
//
// Награда: исход двух боёв (со сменой сторон) собранного босса против босса соперника; единственная награда в конце сборки, дисконт 1,
// ценность считает сама сеть (A2C с GAE). Две сети A и B растут одновременно (соперник: другая сеть сейчас, зал славы, обычный генератор).
//
//   ./net_builder train <итераций> <сборок на сторону> <зерно> <префикс весов> [стартовые A.bin] [стартовые B.bin]
//   ./net_builder eval  <веса> <сборок>             — против обычного генератора и против линейных Сборщиков (builder_runs/v4_champ_*.txt)
//   ./net_builder show  <веса> <сколько>            — описания собранных боссов
//   ./net_builder replay <A.bin> <B.bin> <бюджет> <зерно> <файл.html> — бой боссов двух сетей-Сборщиков для просмотрщика
// Сборка: g++ -std=c++17 -O2 -pthread -o net_builder net_builder.cc
// ============================================================================
#define main boss_main
#include "boss_arena_v20.cc"
#undef main
#include <cstdio>
#include <fstream>
#include <sstream>
#include "gru.h"
#include "par.h"
#include "builder_net.h"

int main(int argc, char** argv) {
    g_rlTurn = nullptr;
    if (argc > 1 && std::string(argv[1]) == "train") return bld::trainMain(argc, argv);
    if (argc > 1 && std::string(argv[1]) == "eval") return bld::evalMain(argc, argv);
    if (argc > 1 && std::string(argv[1]) == "show") return bld::showMain(argc, argv);
    if (argc > 1 && std::string(argv[1]) == "report") return bld::reportMain(argc, argv);
    if (argc > 1 && std::string(argv[1]) == "replay") return bld::replayMain(argc, argv);
    std::fprintf(stderr, "использование: net_builder train|eval|show (см. шапку файла)\n");
    return 1;
}
