double tierN(int id, double n) {
    if (n <= 0) return 0;
    const TierDef& d = TD[id];
    const double sc = d.e == 0 ? 1.0 : std::exp(d.e * std::log(g_B / 1600.0)), a = d.a * sc, b = d.b * sc;
    double g = std::min(n, a);
    if (n > a) {
        double t = std::min(n, b) - a;
        g += t + d.k2 * t * (t + 1) / 2;
    }
    if (n > b) {
        // s3 не выше P: после b цена ступени только замедляется
        double u = n - b, P = 1 + d.k2 * (b - a), s3 = std::min(d.s3, P), q = std::exp(-1.0 / d.c);
        g += s3 * u + (P - s3) * q * (1 - std::pow(q, u)) / (1 - q);
    }
    return d.q == 0 ? g : g * std::exp(d.q * std::log(g_B / 1600.0));
}
