// Цена n-й ступени m(n), в единицах базовой ступени (коэффициент атома из AD[] умножается на tierN). Форма роста:
//   n <= a        : m = 1                                   (медленный рост, как в v19: калибровка этого участка не
//   меняется) a < n <= b    : m = 1 + k2*(n-a)                        (быстрый рост цены ступени) n > b         : m =
//   s3 + (P - s3)*exp(-(n-b)/c),  P = m(b)   (рост цены ступени замедляется до s3, но остаётся выше начального: s3 >=
//   1)
// tierN(n) = m(1)+...+m(n): цена и её производная непрерывны, ступень никогда не дешевле базовой (m >= 1).
// Пороги a и b зависят от бюджета: a(B) = a·(B/1600)^e. Все шесть чисел (a, b, k2, s3, c, e) каждой лестницы подбирает
// замер (builder tiers).
enum Tier {
    TR_RANGE,
    TR_AREA,
    TR_PUSH,
    TR_TELE,
    TR_SPEED,
    TR_AURARAD,
    TR_AURADICE,
    TR_DMG,
    TR_TEMP,
    TR_ACB,
    TR_ATT,
    TR_NABIL,
    TR_N
};
// e — показатель: пороги a и b умножаются на (бюджет/1600)^e; q — показатель: вся цена умножается на (бюджет/1600)^q
struct TierDef {
    const char* name;
    double a, b, k2, s3, c, e, q;
};
