// Проверка границ таблицы при запуске любой программы, собранной с движком: предупреждение для каждого нарушенного атома
bool adBoundsOk(bool report) {
    bool ok = true;
    for (int a = 0; a < AT_N; a++)
        if (!(AD[a].lo <= AD[a].init && AD[a].init <= AD[a].hi)) {
            ok = false;
            if (report)
                std::fprintf(stderr, "ВНИМАНИЕ: атом %d «%s»: нарушено lo <= init <= hi (lo %g, init %g, hi %g)\n", a,
                             AD[a].name, AD[a].lo, AD[a].init, AD[a].hi);
        }
    return ok;
}
