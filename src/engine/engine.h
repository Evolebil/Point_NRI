// Арена Боссов: движок целиком (подключать этот файл)
// Босс собирается из АТОМОВ на бюджет очков; цены атомов калибруются симуляцией: владелец атома выигрывает ~50% боёв.
// Правила и таблица цен: docs/pravila-v21.md. Проверки: tests/audit_tests.cc (+ tests/audit/). Замер лестниц: src/apps/tiers.cc.
//
// Порядок сборки босса:
//   характеристики (ХАР покупается как остальные) → КД и ХП → оружие (кубики, дальность, досягаемость, число атак,
//   запасное оружие, довесок) → способности из атомов (доставка, область, дальность, применения, ячейки, перезарядка,
//   концентрация; нагрузка: урон, 15 состояний, урон по времени, толчок, телепорт, лечение, баффы, тьма, невидимость)
//   → пассивы и защиты → миньоны (шаблон + копии, командует главный босс) → остаток в ХП.
// Карта: 100×100 клеток по 5 фт, стены, залезаемые препятствия, труднопроходимая местность, тьма.
// Бой: инициатива, ход = движение + действие + бонусное действие + реакция.
// НЕ РЕАЛИЗОВАНО: см. docs/pravila-v21.md.
//
// Части (по порядку, один блок трансляции — порядок важен): core → atoms → spec → gen_spec → gen_boss → world → rules
// → eval → actions → turn → bot → arena_map → chase → fight (подключает human_turn, prim_net, custom_map) → describe
// → calib (replay_export, par, builder_net). Программы — src/apps/ (arena.cc — калибровка и просмотр).
//
// Случайные числа: свой xorshift64* (Rng), результат по зерну одинаков на любом компиляторе. Всё изменяемое состояние
// боя — thread_local; калибровка идёт параллельно, итог не зависит от числа потоков (DND_THREADS, по умолчанию ядра − 2).
//
// Сборка всех программ: make
// ============================================================================

